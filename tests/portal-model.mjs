import assert from 'node:assert/strict';
import {normalizeURL, normalizeHost, mergeIdentities, isIdentity, bestURL, addressSpace} from '../portal/hosts.mjs';
assert.equal(normalizeURL('192.168.1.2'), 'http://192.168.1.2:8765');
assert.equal(normalizeURL('mac.local:9000'), 'http://mac.local:9000');
assert.equal(normalizeURL('https://mac.local/terminal/demo'), 'https://mac.local');
assert.equal(normalizeURL('[::1]:8765'), 'http://[::1]:8765');
for (const input of ['javascript://alert(1)', 'ftp://mac.local', 'http://u:p@mac.local']) assert.throws(() => normalizeURL(input));
assert.equal(addressSpace('http://localhost:8765'), 'loopback');
assert.equal(addressSpace('http://192.168.1.2:8765'), 'local');
assert.equal(addressSpace('http://100.66.11.2:8765'), 'local');
assert.equal(addressSpace('http://100.128.0.1:8765'), undefined);
const id = '1a1ba1ee-eff2-7e81-8f6e-1933661ea66c';
const other = '2a1ba1ee-eff2-7e81-8f6e-1933661ea66c';
const identity = {service:'openremotehub', protocol:1, instance_id:id, name:'Mac mini'};
assert.equal(isIdentity(identity), true);
assert.equal(isIdentity({...identity, service:'router'}), false);
assert.equal(isIdentity({...identity, instance_id:'not-a-uuid'}), false);
const a = normalizeHost({urls:['192.168.1.2', '192.168.1.2/']});
assert.equal(a.urls.length, 1);
const b = normalizeHost({urls:['10.77.1.2']});
const results = new Map([[a.urls[0], {identity, latency:20}], [b.urls[0], {identity, latency:10}]]);
const merged = mergeIdentities([a,b], results);
assert.equal(merged.length, 1);
assert.equal(merged[0].name, 'Mac mini');
assert.equal(merged[0].urls.length, 2);
assert.equal(bestURL(merged[0], results), b.urls[0]);
merged[0].preferred = a.urls[0];
assert.equal(bestURL(merged[0], results), a.urls[0]);
results.set(b.urls[0], {identity:{...identity, instance_id:other, name:'Linux'}, latency:10});
const split = mergeIdentities(merged, results);
assert.equal(split.length, 2, 'different devices must split even if entered in one card');
assert.equal(new Set(split.map(host => host.id)).size, 2);
assert.equal(mergeIdentities([a,b], new Map()).length, 2, 'unverified hosts cannot merge by name');
console.log('Portal model: URL validation, identity checks, multi-address merge, split and reachable address choice passed.');
